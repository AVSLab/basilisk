"""Generate on-demand FSW import shims and clean up a previous build layout."""

import importlib.machinery
from pathlib import Path
import re
import sys

SHIM = """# Generated by generateFswBindings.py; do not edit.
from ._load_fsw import load_native_module as _load_native_module
_load_native_module(__name__)
del _load_native_module
"""


def write_if_changed(path: Path, content: str) -> None:
    """Write a generated file only when its contents change."""
    if not path.exists() or path.read_text() != content:
        path.write_text(content)


def read_names(path: Path) -> set[str]:
    """Read and validate a manifest of module names."""
    names = set(path.read_text().split()) if path.exists() else set()
    if any(re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", name) is None for name in names):
        raise ValueError(f"Invalid FSW module name in {path}")
    return names


def remove_native(package_dir: Path, name: str) -> None:
    """Remove only a named extension's platform-specific build outputs."""
    for suffix in importlib.machinery.EXTENSION_SUFFIXES:
        (package_dir / f"_{name}{suffix}").unlink(missing_ok=True)


def generate_layout(manifest: Path, package_dir: Path, loader: Path) -> None:
    """Update the package layout when the experimental build option changes.

    :param manifest: Manifest of bindings in the combined library, empty when disabled.
    :param package_dir: Generated FSW Python package directory.
    :param loader: Source file for the combined-library loader.
    """
    names = read_names(manifest)
    previous = manifest.with_suffix(".previous.txt")
    old_names = read_names(previous)
    package_dir.mkdir(parents=True, exist_ok=True)
    for name in old_names - names:
        (package_dir / f"_{name}.py").unlink(missing_ok=True)
    for name in names:
        remove_native(package_dir, name)
        write_if_changed(package_dir / f"_{name}.py", SHIM)
    if names:
        write_if_changed(package_dir / "_load_fsw.py", loader.read_text())
    else:
        (package_dir / "_load_fsw.py").unlink(missing_ok=True)
        remove_native(package_dir, "fswCoreNative")
    write_if_changed(previous, manifest.read_text())


if __name__ == "__main__":
    generate_layout(*(Path(argument) for argument in sys.argv[1:]))
