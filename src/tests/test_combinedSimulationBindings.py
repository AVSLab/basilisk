"""Check grouped simulation and optional imports without changing their public APIs."""

import importlib
import importlib.machinery
import importlib.util
from pathlib import Path
import re
import subprocess
import sys

import pytest
from Basilisk import fswAlgorithms, hasBuildFeature, simulation


GROUPS = (
    ("Basilisk.simulation._simulationCoreNative", "simulation", "spacecraft", "Spacecraft"),
    pytest.param("Basilisk.simulation._mujocoNative", "simulation", "thrOnTimeToForce", "ThrOnTimeToForce",
                 marks=pytest.mark.skipif(not hasBuildFeature("mujoco"), reason="MuJoCo support is disabled")),
    pytest.param("Basilisk._opNavNative", "simulation", "camera", "Camera",
                 marks=pytest.mark.skipif(not hasBuildFeature("opNav"), reason="OpenCV support is disabled")),
)


@pytest.mark.parametrize("library,package,name,class_name", GROUPS)
def test_grouped_imports_preserve_proxies_and_private_modules(library, package, name, class_name):
    """Every grouped private extension retains its original Python proxy and reload identity.

    :param library: Name of the optional native container.
    :param package: Package containing the representative binding.
    :param name: Representative public module name.
    :param class_name: Representative constructor name.
    """
    spec = importlib.util.find_spec(library)
    assert spec is not None, f"Required native binding group is missing: {library}"
    count = 0
    for parent in (fswAlgorithms, simulation):
        directory = Path(parent.__file__).parent
        proxies = {}
        for path in directory.glob("*.py"):
            text = path.read_text(encoding="utf-8")
            match = re.search(r"^    from \. import (_[A-Za-z_][A-Za-z_0-9]*)$", text, re.MULTILINE)
            if match:
                proxies[match[1]] = path.stem
        for shim in directory.glob("_*.py"):
            text = shim.read_text(encoding="utf-8")
            if "Generated by generateGroupedBindings.py" not in text or repr(library) not in text:
                continue
            native = importlib.import_module(parent.__name__ + "." + shim.stem)
            proxy = importlib.import_module(parent.__name__ + "." + proxies[shim.stem])
            assert getattr(proxy, shim.stem) is native
            assert importlib.reload(native) is native
            assert getattr(parent, shim.stem) is native
            assert native.__file__ == spec.origin
            count += 1
    assert count > 1
    proxy = importlib.import_module("Basilisk." + package + "." + name)
    assert getattr(proxy, class_name)() is not None


@pytest.mark.parametrize("library,package,name,class_name", GROUPS)
def test_grouped_imports_initialize_only_requested_bindings(library, package, name, class_name):
    """A representative import leaves unrelated native bindings uninitialized.

    :param library: Name of the optional native container.
    :param package: Package containing the representative binding.
    :param name: Representative public module name.
    :param class_name: Representative constructor name.
    """
    assert importlib.util.find_spec(library) is not None, f"Required native binding group is missing: {library}"
    code = """import importlib, sys
from Basilisk import architecture
module = importlib.import_module(sys.argv[1])
assert getattr(module, sys.argv[2])() is not None
for unrelated in ('Basilisk.simulation._solarFlux', 'Basilisk.simulation._MJSystemCoM',
                  'Basilisk.fswAlgorithms._houghCircles'):
    assert unrelated not in sys.modules, unrelated
"""
    timeout = 60  # [s]
    result = subprocess.run([sys.executable, "-c", code, "Basilisk." + package + "." + name, class_name],
                            capture_output=True, text=True, timeout=timeout)
    assert result.returncode == 0, result.stdout + result.stderr


@pytest.mark.parametrize("import_order", [
    ("gravityEffector", "svIntegrators"),
    ("svIntegrators", "gravityEffector"),
    ("sphericalHarmonicsGravityModel", "svIntegrators"),
    ("svIntegrators", "sphericalHarmonicsGravityModel"),
    pytest.param(
        ("gravityEffector", "mujoco", "svIntegrators"),
        marks=pytest.mark.skipif(not hasBuildFeature("mujoco"), reason="MuJoCo support is disabled"),
    ),
    pytest.param(
        ("svIntegrators", "mujoco", "gravityEffector"),
        marks=pytest.mark.skipif(not hasBuildFeature("mujoco"), reason="MuJoCo support is disabled"),
    ),
    pytest.param(
        ("sphericalHarmonicsGravityModel", "mujoco", "svIntegrators"),
        marks=pytest.mark.skipif(not hasBuildFeature("mujoco"), reason="MuJoCo support is disabled"),
    ),
    pytest.param(
        ("svIntegrators", "mujoco", "sphericalHarmonicsGravityModel"),
        marks=pytest.mark.skipif(not hasBuildFeature("mujoco"), reason="MuJoCo support is disabled"),
    ),
])
@pytest.mark.parametrize("first_use", ["coefficients", "vectors", "integrators"])
def test_shared_vector_conversions_in_fresh_process(import_order, first_use):
    """Keep vector conversions independent of import order and cached type queries.

    Direct and legacy spherical-harmonics imports must expose the same class.

    :param import_order: Public modules to import before using any shared vector.
    :param first_use: Conversion to exercise before SWIG caches its type lookup.
    """
    code = """import importlib, sys
for name in sys.argv[2:]:
    importlib.import_module("Basilisk.simulation." + name)

from Basilisk.architecture import swig_common_model
from Basilisk.simulation import gravityEffector, spacecraft, svIntegrators
from Basilisk.simulation.sphericalHarmonicsGravityModel import SphericalHarmonicsGravityModel

assert gravityEffector.SphericalHarmonics is SphericalHarmonicsGravityModel

tableau = [[0.0, 0.0], [0.5, 0.0]]  # [-]
weights = [0.0, 1.0]  # [-]
nodes = [0.0, 0.5]  # [-]

def coefficients():
    model = gravityEffector.SphericalHarmonics()
    for values in (swig_common_model.MultiArray(tableau), tableau):
        model.cBar = values
        model.sBar = values
        assert [list(row) for row in model.cBar] == tableau
        assert [list(row) for row in model.sBar] == tableau

def vectors():
    matrix = swig_common_model.MultiArray(tableau)
    assert list(matrix[1]) == tableau[1]
    assert [list(row) for row in matrix] == tableau
    vector = swig_common_model.DoubleVector(weights)
    assert vector[1] == weights[1]
    assert list(vector) == weights

def integrators():
    body = spacecraft.Spacecraft()
    for matrix, vector in (
        (swig_common_model.MultiArray, swig_common_model.DoubleVector),
        (list, list),
    ):
        fixed = svIntegrators.svIntegratorRungeKutta2(
            body, matrix(tableau), vector(weights), vector(nodes))
        adaptive = svIntegrators.svIntegratorAdaptiveRungeKutta2(
            body, matrix(tableau), vector(weights), vector([1.0, 0.0]),
            vector(nodes), 2.0)  # [-] Embedded weights and method order
        assert fixed.getDynamicsCount() == 1
        assert adaptive.getDynamicsCount() == 1

checks = dict(coefficients=coefficients, vectors=vectors, integrators=integrators)
checks.pop(sys.argv[1])()
for check in checks.values():
    check()
"""
    timeout = 60  # [s]
    result = subprocess.run(
        [sys.executable, "-c", code, first_use, *import_order],
        capture_output=True, text=True, timeout=timeout,
    )
    assert result.returncode == 0, result.stdout + result.stderr


@pytest.mark.parametrize("suffix", importlib.machinery.EXTENSION_SUFFIXES)
def test_group_layout_cleanup_preserves_other_groups(tmp_path, suffix):
    """Switching a cross-package group leaves adjacent native modules and loaders intact.

    :param tmp_path: Temporary directory supplied by pytest.
    :param suffix: Native extension suffix supported by the active Python interpreter.
    """
    source = Path(__file__).resolve().parents[1]
    spec = importlib.util.spec_from_file_location("generateGroupedBindings", source / "cmake/generateGroupedBindings.py")
    generator = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(generator)
    manifest = tmp_path / "group.txt"
    package = tmp_path / "Basilisk"
    manifest.write_text("simulation.first\nfswAlgorithms.second\n")
    loader = source / "fswAlgorithms/_load_fsw.py"
    (package / "simulation").mkdir(parents=True)
    for name in ("first.lib", "_first.lib"):
        (package / "simulation" / name).touch()
    generator.generate_layout(manifest, package, loader, "_opNavNative", "_load_opnav", manifest)
    assert not list((package / "simulation").glob("*.lib"))
    first = package / "simulation/_first.py"
    stamp = first.stat().st_mtime_ns
    generator.generate_layout(manifest, package, loader, "_opNavNative", "_load_opnav", manifest)
    assert first.stat().st_mtime_ns == stamp
    unrelated = package / f"simulation/_simulationCoreNative{suffix}"
    unrelated.write_bytes(b"other group")
    native = package / f"_opNavNative{suffix}"
    native.touch()
    archive = package / "_opNavNative.lib"
    archive.touch()
    manifest.write_text("")
    generator.generate_layout(manifest, package, loader, "_opNavNative", "_load_opnav", manifest)
    assert not first.exists()
    assert not (package / "fswAlgorithms/_second.py").exists()
    assert not (package / "_load_opnav.py").exists()
    assert not native.exists()
    assert not archive.exists()
    assert unrelated.read_bytes() == b"other group"
